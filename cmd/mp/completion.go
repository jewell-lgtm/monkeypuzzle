package mp

import (
	"os"

	"github.com/spf13/cobra"
)

var completionCmd = &cobra.Command{
	Use:   "completion [bash|zsh|fish|powershell]",
	Short: "Generate shell completion script",
	Long: `Generate completion script for your shell.

bash:
  source <(mp completion bash)
  # Or add to ~/.bashrc

zsh:
  mp completion zsh > "${fpath[1]}/_mp"
  # Or: source <(mp completion zsh)

fish:
  mp completion fish | source
  # Or: mp completion fish > ~/.config/fish/completions/mp.fish

powershell:
  mp completion powershell | Out-String | Invoke-Expression`,
	Args:      cobra.ExactValidArgs(1),
	ValidArgs: []string{"bash", "zsh", "fish", "powershell"},
	RunE: func(cmd *cobra.Command, args []string) error {
		switch args[0] {
		case "bash":
			return rootCmd.GenBashCompletion(os.Stdout)
		case "zsh":
			return rootCmd.GenZshCompletion(os.Stdout)
		case "fish":
			return rootCmd.GenFishCompletion(os.Stdout, true)
		case "powershell":
			return rootCmd.GenPowerShellCompletionWithDesc(os.Stdout)
		}
		return nil
	},
}

func init() {
	rootCmd.AddCommand(completionCmd)
}
